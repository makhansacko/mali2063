      <!-- INTRO -->

      <p class="intro">
        La Vision Mali Kura 2063 fixe une ambition claire : transformer structurellement l’économie malienne. Mais cette transformation ne dépend pas uniquement des infrastructures, des investissements ou de la recherche scientifique. Elle dépend aussi de la capacité des entreprises à apprendre, adapter, améliorer et produire autrement.
      </p>

      <p>
        Or, le système d’innovation malien reste principalement organisé autour de la production de connaissances scientifiques, avec beaucoup moins d’attention portée à la transformation productive réelle des entreprises. C’est probablement le principal angle mort de notre politique d’innovation actuelle.
      </p>

      <!-- SECTION 1 -->

      <h2 class="section-title">La Vision et son impératif d’innovation</h2>

      <p>
        Dans mes précédents posts sur la Vision Mali Kura 2063, j’ai décrit plusieurs ambitions portées par ce cadre de développement national : réduire la pauvreté de 43,9 % à 10 %, atteindre l’accès universel à l’électricité, développer les infrastructures ferroviaires, renforcer l’industrialisation et faire du Mali un hub technologique pour l’Afrique de l’Ouest.
      </p>

      <p>
        Ces objectifs ont un point commun : ils supposent une transformation structurelle profonde de l’économie malienne.
      </p>

      <p>
        Autrement dit, le passage progressif d’une économie dominée par l’extraction et l’agriculture de subsistance à une économie plus productive, plus industrielle, plus diversifiée et capable de créer davantage de valeur ajoutée localement.
      </p>

      <p>
        Mais la transformation structurelle ne se décrète pas.
      </p>

      <p>
        Elle se construit entreprise par entreprise, filière par filière, à travers l’introduction de nouveaux procédés, l’amélioration de la production, l’adaptation de technologies existantes et l’émergence de nouvelles organisations productives.
      </p>

      <p>
        En un mot : à travers l’innovation.
      </p>

      <blockquote class="pull-quote">
        La transformation structurelle que vise la Vision Mali 2063 ne peut pas reposer uniquement sur un système d’innovation conçu pour produire des publications scientifiques. Elle exige un système capable de transformer concrètement la pratique productive des entreprises.
      </blockquote>

      <p>
        La Vision reconnaît explicitement l’importance de l’innovation — notamment à travers le projet structurant consacré à l’innovation et à la digitalisation. Mais reconnaître l’importance de l’innovation ne suffit pas. Encore faut-il définir correctement ce qu’innover signifie dans le contexte malien.
      </p>

      <!-- SECTION 2 -->

      <h2 class="section-title">Une définition de l’innovation inadaptée à l’ambition</h2>

      <p>
        Le Plan Stratégique National de la Recherche et de l’Innovation (PSNRI 2025-2034) constitue aujourd’hui le principal instrument chargé d’opérationnaliser cette ambition du côté de la recherche et de la technologie.
      </p>

      <p>
        Le document est sérieux. Il représente un effort réel de coordination institutionnelle et de structuration du système national de recherche. Mais il repose encore sur une conception de l’innovation trop étroite pour répondre pleinement aux objectifs de transformation économique de la Vision Mali 2063.
      </p>

      <p>
        Le PSNRI adopte implicitement une logique linéaire : la recherche produit des connaissances, qui se transforment ensuite en innovations diffusées dans l’économie.
      </p>

      <p>
        Dans cette logique, innover signifie d’abord produire de la nouveauté scientifique : publications, variétés agricoles homologuées, prototypes validés ou brevets.
      </p>

      <p>
        Le problème est que cette conception correspond peu à la réalité productive de la majorité des entreprises maliennes.
      </p>

      <p>
        Dans les économies où le système national d’innovation reste émergent, les entreprises innovent rarement par invention radicale. Elles innovent surtout par adaptation de technologies existantes, amélioration incrémentale des procédés et optimisation de la production.
      </p>

      <p>
        Dan Breznitz pousse cette idée plus loin en distinguant plusieurs formes d’innovation productive : la création de nouveauté, mais aussi le prototypage, l’ingénierie de production, l’amélioration incrémentale et l’optimisation des procédés industriels.
      </p>

      <p>
        Or, la grande majorité des entreprises maliennes — agro-transformateurs, artisans, PME manufacturières, unités informelles de production — innovent principalement dans ces derniers segments.
      </p>

      <p>
        Le PSNRI, lui, reste largement calibré pour le premier.
      </p>

      <p>
        Cette distinction est fondamentale.
      </p>

      <p>
        Car les ambitions de la Vision Mali 2063 — agropoles, industrialisation, montée en gamme des filières agricoles, développement de chaînes de valeur locales — supposent surtout des entreprises capables :
      </p>

      <ul class="article-list">
        <li>d’améliorer leurs procédés ;</li>
        <li>d’adapter des technologies existantes ;</li>
        <li>d’optimiser leur production ;</li>
        <li>de produire à meilleure qualité et à plus grande échelle.</li>
      </ul>

      <p>
        Un système centré presque exclusivement sur la production scientifique ne suffit pas à construire ces capacités productives.
      </p>

      <!-- SECTION 3 -->

      <h2 class="section-title">Le chaînon manquant : entre la recherche et l’entreprise</h2>

      <p>
        La deuxième limite du système actuel est institutionnelle.
      </p>

      <p>
        Même lorsque des connaissances utiles sont produites, rien ne garantit qu’elles atteignent les entreprises capables de les utiliser.
      </p>

      <p>
        Il manque ce que plusieurs chercheurs appellent le “missing middle” : les organisations intermédiaires qui assurent le lien entre la recherche et la pratique productive.
      </p>

      <p>
        Centres techniques, services d’extension, conseillers industriels, unités de démonstration technologique, structures de transfert technologique — autant d’institutions largement absentes ou insuffisamment opérationnelles dans le contexte malien.
      </p>

      <p>
        Le paradoxe est d’ailleurs reconnu par le PSNRI lui-même : près de 40 % des entreprises maliennes ont introduit un produit ou un procédé nouveau entre 2017 et 2019, souvent sans interaction avec le système formel de recherche.
      </p>

      <p>
        Autrement dit, l’innovation existe déjà.
      </p>

      <p>
        Mais elle se développe de manière fragmentée, informelle et sans véritable infrastructure institutionnelle capable :
      </p>

      <ul class="article-list">
        <li>de faire remonter les besoins techniques des entreprises ;</li>
        <li>de diffuser les connaissances existantes ;</li>
        <li>d’accompagner l’adoption technologique ;</li>
        <li>ou de transformer les apprentissages locaux en capacités productives durables.</li>
      </ul>

